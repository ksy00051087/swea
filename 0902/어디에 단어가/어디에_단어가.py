import sys
sys.stdin = open('input.txt', 'r')

"""
[SWEA] 단어 퍼즐 - N x N 퍼즐에서 길이가 정확히 K인 단어가 들어갈 자리의 개수

문제 요약
---------
- N x N 격자. 1 = 흰색(글자 쓸 수 있음), 0 = 검은색(막힌 칸)
- 가로 방향, 세로 방향 각각에서 '연속된 흰 칸 덩어리'의 길이가 정확히 K인 곳을 센다
- 제약: 5 ≤ N ≤ 15,  2 ≤ K ≤ N

핵심 아이디어 : "길이가 정확히 K" 의 의미
----------------------------------------
가장 많이 틀리는 지점이다. K=3 이고 흰 칸이 4개 연속(1 1 1 1)이면?

  → 답은 0곳이다. 1곳도, 2곳도 아니다.

왜냐하면 단어 퍼즐에서 한 자리(entry)는 검은 칸이나 격자 끝에서 시작해
검은 칸이나 격자 끝에서 끝나는 '덩어리 전체'를 말하기 때문이다.
길이 4짜리 덩어리에 길이 3짜리 단어를 넣으면 칸 하나가 남으므로 그 자리가 아니다.

즉 우리가 셀 것은:
  "연속된 1의 덩어리(maximal run)를 잘라내서, 그 길이가 == K 인 덩어리의 개수"
  ('>= K' 가 아니라 '== K' 다!)

풀이 방법 : 연속 카운트
---------------------
한 줄을 왼쪽부터 훑으면서 1이면 cnt += 1, 0을 만나면 덩어리가 끝난 것이므로
그 순간 cnt == K 인지 검사하고 cnt를 0으로 리셋한다.
줄 끝에 도달했을 때도 덩어리가 안 끝난 상태일 수 있으므로 마지막에 한 번 더 검사해야 한다.
   ↑ 이 '줄 끝 처리'를 빼먹는 게 두 번째로 흔한 실수다.

이것을 가로 N줄, 세로 N줄에 대해 똑같이 수행하고 합친다.

시간복잡도
---------
가로 N^2 + 세로 N^2 = O(N^2). N=15여도 450칸. T=10이면 사실상 즉시 끝난다.
"""

import sys

# 로컬 테스트용. SWEA 제출 시 반드시 주석 처리!
# sys.stdin = open('input.txt', 'r')

input = sys.stdin.readline


def count_in_line(line, K):
    """1차원 리스트(한 줄)에서 '연속된 1의 길이가 정확히 K'인 덩어리 개수를 센다."""
    count = 0
    cnt = 0  # 현재 이어지고 있는 1의 개수

    for v in line:
        if v == 1:
            cnt += 1          # 덩어리가 계속 이어짐
        else:
            # 0을 만났다 = 방금까지의 덩어리가 여기서 끝났다
            if cnt == K:
                count += 1
            cnt = 0           # 다음 덩어리를 위해 리셋

    # ★ 줄이 1로 끝난 경우, 위 for문 안에서는 검사할 기회가 없었다.
    #   반드시 반복문 밖에서 한 번 더 확인해야 한다.
    if cnt == K:
        count += 1

    return count


def solve_one_case():
    """테스트 케이스 하나를 처리해서 자리의 총 개수를 반환한다."""

    N, K = map(int, input().split())

    # N줄의 퍼즐 모양을 2차원 리스트로 읽는다
    # (입력 줄 끝에 공백이 붙어 있어도 split()이 알아서 걸러준다)
    board = [list(map(int, input().split())) for _ in range(N)]

    answer = 0

    # ── 1) 가로 방향 : board의 각 행을 그대로 넘기면 된다 ──
    for r in range(N):
        answer += count_in_line(board[r], K)

    # ── 2) 세로 방향 : c번째 열을 위에서 아래로 모아 리스트로 만든다 ──
    for c in range(N):
        column = [board[r][c] for r in range(N)]   # 행 인덱스 r이 변하는 것에 주의
        answer += count_in_line(column, K)

    return answer


def main():
    T = int(input())
    for tc in range(1, T + 1):
        print(f'#{tc} {solve_one_case()}')


main()


